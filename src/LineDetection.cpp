double LineDetection::getLineAngle(int sensNum1, int sensNum2) {
    Point p1 = points[sensNum1];
    Point p2 = points[sensNum2];

    double slope = Trig::getSlope(p1, p2);
    // double perpendicularSlope = -1 / slope; // shouldn't need this I think

    double angle = atan2(-slope, 1.0) * 180 / M_PI;
    return angle;
}